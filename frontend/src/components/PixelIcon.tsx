export type IconName = keyof typeof SPRITES

type Props = {
  name: IconName
  /** Lado del icono en píxeles de pantalla. Múltiplos de 16 quedan nítidos. */
  size?: number
  className?: string
  /** Texto accesible. Sin él, el icono se marca como decorativo. */
  title?: string
}

export function PixelIcon({ name, size = 16, className, title }: Props) {
  const { rects } = parseSprite(SPRITES[name], PALETTE)

  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      role={title ? 'img' : 'presentation'}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} fill={r.fill} />
      ))}
    </svg>
  )
}
